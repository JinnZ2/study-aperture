"""CONSTRUCTED equation substitution, no claims about a physical instrument.

From experimental/: python3 -m playground.equations.example
Emits both immutable run records, linked by the second run's parent digest.
"""

import json
from dataclasses import replace

from ..applicability.example import DECISION, fixture
from ..failures import EvidenceRef
from ..gates.l0_closure import (
    BoundaryAccounting, Direction, Exchange, QuantityAccount, ValueProvenance,
)
from ..reference.anchor import AnchorState
from ..validation.known_answer import KnownAnswerCase
from ..validation.null_harness import NullCase
from .adapter import Equation, EquationRegistry, InputPort, OutputPort
from .substitution import BoundaryProtocol, Experiment, ValidationPlan, execute, substitute


def fixture_equation(expression="x", revision="1", equation_id="toy-equation") -> Equation:
    profile, _ = fixture()
    return Equation(
        equation_id, revision, "constructed finite-window response y",
        (InputPort("x", "energy", "toy-energy-unit"),),
        (OutputPort("y", expression, "toy-energy-unit"),),
        profile.constraints, DECISION,
        (EvidenceRef("constructed-definition", "equations/example.py:fixture_equation"),),
    )


def fixture_experiment() -> Experiment:
    _, context = fixture()
    anchor = AnchorState.from_maps("anchor-A-v1", {"energy": 2.0},
                                   ("constructed fixed reference",))
    context = replace(context, anchor_digest=anchor.digest())
    ledger = BoundaryAccounting(
        "selected-cell-A",
        (QuantityAccount(
            "energy", 2.0, 2.0, ValueProvenance.SPECIFIED, ValueProvenance.SPECIFIED,
            (
                Exchange("energy", Direction.INFLOW, 0.0, "zero-drive-exchange",
                         ValueProvenance.SPECIFIED, "control:drive"),
                Exchange("energy", Direction.OUTFLOW, 0.0, "zero-observer-exchange",
                         ValueProvenance.SPECIFIED, "observer:sensor"),
            ),
            0.0,
        ),),
        True, ("control:drive", "observer:sensor"),
    )
    binding = BoundaryProtocol(
        context.digest(), anchor.digest(), ledger, (("energy", "toy-energy-unit"),),
        (("control:drive", "control"), ("observer:sensor", "observer")), DECISION,
    )
    return Experiment(context, anchor, binding)


def fixture_plan(equation: Equation, experiment: Experiment, doubled=False) -> ValidationPlan:
    # These are explicit synthetic expectations, NOT outputs generated by
    # the equation under test.
    expected = (1.0, 2.0) if not doubled else (2.0, 4.0)
    cases = tuple(
        KnownAnswerCase.from_maps(
            f"known-{x:g}", {"x": x}, {"y": y}, {"y": 1e-12},
            "CONSTRUCTED, hand-stated arithmetic expectation",
        )
        for x, y in zip((1.0, 2.0), expected)
    )
    return ValidationPlan(
        "constructed-plan", equation.digest(), experiment.context.digest(), cases,
        (NullCase.from_maps("zero-input", {"x": 0.0}, {"y": 0.0}, {"y": 0.0}),),
        (("x", "toy-energy-unit"),), (("y", "toy-energy-unit"),), DECISION,
        (EvidenceRef("constructed-criteria", "equations/example.py:fixture_plan"),),
    )


def example_runs():
    first = fixture_equation()
    second = fixture_equation("2*x", revision="2")
    registry = EquationRegistry()
    registry.register(first)
    registry.register(second)
    experiment = fixture_experiment()
    a = execute(registry, first.equation_id, first.revision, experiment,
                fixture_plan(first, experiment), DECISION)
    b = substitute(a, registry, second.equation_id, second.revision,
                   fixture_plan(second, experiment, doubled=True), DECISION)
    return a, b


if __name__ == "__main__":
    print(json.dumps({
        "status": "CONSTRUCTED example, not physical validation",
        "runs": [run.to_dict() for run in example_runs()],
    }, indent=2, sort_keys=True, allow_nan=False))
