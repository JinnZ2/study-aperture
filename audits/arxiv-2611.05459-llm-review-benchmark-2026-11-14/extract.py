#!/usr/bin/env python3
"""extract.py -- verify and render the quotes extracted from arXiv 2611.05459v1.

Co-authored. CC0. Stdlib only, no network.

  python3 extract.py --verify ABS_HTML PAPER_HTML PAPER_PDF_TEXT
        Checks every quote in quotes.json verbatim (whitespace-normalised)
        against the paper text, finds its PDF page, writes located.json and
        EXTRACT.md. Needs the three locally fetched files (not committed;
        their sha256 are in manifest.json). PAPER_PDF_TEXT is
        `pdftotext -layout` output; pages are split on form feeds.
  python3 extract.py --check
        No paper needed. Checks structure: items 1-7 and the frame item are
        present, every UNKNOWN entry names its field and what was searched,
        every quote was located, and EXTRACT.md equals the render of
        quotes.json + located.json.

A quote that is not found verbatim is a failure, never silently kept.
"""
import html
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
QUOTES = HERE / "quotes.json"
LOCATED = HERE / "located.json"
EXTRACT = HERE / "EXTRACT.md"
REQUIRED_ITEMS = [1, 2, 3, 4, 5, 6, 7, "frame"]


def norm(s):
    return " ".join(s.split())


def squash(s):
    """For locating a PDF page only: drop whitespace, hyphens and quote marks
    (pdftotext splits lines inside hyphenated words). Verbatim checks use norm()."""
    return re.sub(r"[\s\-\u2010\u2011\u201c\u201d\u2018\u2019\"'`]", "", s)


def html_text(raw):
    raw = re.sub(r"<(script|style)[^>]*>.*?</\1>", "", raw, flags=re.S)
    raw = re.sub(r"<[^>]+>", " ", raw)
    return norm(html.unescape(raw))


def entries(data):
    for it in data["items"]:
        for e in it["entries"]:
            yield it, e


def key(it, i):
    return f"{it['item']}.{i}"


def verify(abs_path, html_path, pdf_txt_path):
    data = json.loads(QUOTES.read_text(encoding="utf-8"))
    paper = html_text(Path(html_path).read_text(encoding="utf-8"))
    listing = html_text(Path(abs_path).read_text(encoding="utf-8"))
    pages = Path(pdf_txt_path).read_text(encoding="utf-8").split("\f")
    # drop running page-number lines so a quote across a page break still matches
    sq_pages = [squash(re.sub(r"(?m)^\s*\d+\s*$", "", p)) for p in pages]
    located, bad = {}, []
    for it in data["items"]:
        for i, e in enumerate(it["entries"]):
            q = e.get("quote")
            if q is None and "table" in e:
                cells = [c for row in e["table"] for c in row]
                ok = all(norm(c) in paper for c in cells)
                pg = next((n for n, p in enumerate(sq_pages, 1)
                           if all(squash(c) in p for c in e["table"][0])), None)
                located[key(it, i)] = {"verbatim": ok, "pdf_page": pg, "source": "html"}
                if not ok:
                    bad.append(key(it, i))
                continue
            if q is None:
                continue
            src = e.get("quote_source", "html")
            text = listing if src == "abs" else paper
            ok = norm(q) in text
            pg = None
            if src != "abs":
                probe = squash(q)[:80]
                pg = next((n for n, p in enumerate(sq_pages, 1) if probe in p), None)
                if pg is None:  # quote runs across a page break: report the first page
                    pg = next((n for n in range(1, len(sq_pages))
                               if probe in sq_pages[n - 1] + sq_pages[n]), None)
            located[key(it, i)] = {"verbatim": ok, "pdf_page": pg, "source": src}
            if not ok:
                bad.append(key(it, i))
    LOCATED.write_text(json.dumps(located, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    EXTRACT.write_text(render(data, located), encoding="utf-8")
    for b in bad:
        print("NOT VERBATIM:", b)
    n = len(located)
    print(f"{n - len(bad)}/{n} quotes verbatim; "
          f"{sum(1 for v in located.values() if v['pdf_page'])} with a PDF page")
    return 1 if bad else 0


def where(e, loc):
    if e.get("quote_source") == "abs":
        return f"{e['section']}; arXiv abs page"
    pg = loc.get("pdf_page") if loc else None
    return f"§{e['section']}; PDF p. {pg if pg else 'NOT LOCATED'}"


def render(data, located):
    out = ["# Extract: arXiv 2611.05459v1", "",
           "Generated by `extract.py --verify` from `quotes.json`; do not hand-edit.",
           "Quotes only. Section numbers are the paper's; PDF pages are of",
           "`https://arxiv.org/pdf/2611.05459` (sha256 in `manifest.json`).",
           "UNKNOWN = no passage in the paper; it names the field and what was searched.",
           "Reasoning is in `CHECKS.md`, not here.", ""]
    for it in data["items"]:
        label = it["item"] if it["item"] != "frame" else "F"
        out.append(f"## {label}. {it['topic']}")
        out.append("")
        for i, e in enumerate(it["entries"]):
            loc = located.get(key(it, i))
            if e.get("quote") is None and "table" in e:
                out.append(f"- {where(e, loc)}:")
                out.append("")
                out.append("  | tool | underlying model | type | plan | tasks |")
                out.append("  |---|---|---|---|---|")
                for row in e["table"]:
                    out.append("  | " + " | ".join(row) + " |")
                out.append("")
            elif e.get("quote") is None:
                out.append(f"- **UNKNOWN**: {e['field']}. Searched: {e['searched']}.")
            else:
                out.append(f"- > {e['quote']}")
                out.append(f"  ({where(e, loc)})")
        out.append("")
    return "\n".join(out)


def check():
    data = json.loads(QUOTES.read_text(encoding="utf-8"))
    errs = []
    have = [it["item"] for it in data["items"]]
    for r in REQUIRED_ITEMS:
        if r not in have:
            errs.append(f"item {r} missing")
    located = json.loads(LOCATED.read_text(encoding="utf-8")) if LOCATED.exists() else {}
    for it in data["items"]:
        if not it["entries"]:
            errs.append(f"item {it['item']} has no entries")
        for i, e in enumerate(it["entries"]):
            k = key(it, i)
            if e.get("quote") is None and "table" not in e:
                if e.get("section") != "UNKNOWN" or not e.get("field") or not e.get("searched"):
                    errs.append(f"{k}: an absent quote must be UNKNOWN with field and searched")
                continue
            if e.get("quote") is not None and not e["quote"].strip():
                errs.append(f"{k}: empty quote")
            loc = located.get(k)
            if not loc or not loc.get("verbatim"):
                errs.append(f"{k}: not located verbatim")
    if EXTRACT.read_text(encoding="utf-8") != render(data, located):
        errs.append("EXTRACT.md does not match quotes.json + located.json; rerun --verify")
    for e in errs:
        print("FAIL", e)
    n = sum(1 for _ in entries(data))
    print(f"{'PASS' if not errs else 'FAIL'}: {n} entries, {len(located)} located, {len(errs)} problems")
    return 1 if errs else 0


def main(argv):
    if argv[:1] == ["--verify"] and len(argv) == 4:
        return verify(*argv[1:])
    if argv == ["--check"]:
        return check()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
