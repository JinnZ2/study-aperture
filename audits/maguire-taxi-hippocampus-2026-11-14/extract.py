#!/usr/bin/env python3
"""extract.py -- verify and render the quotes extracted for the Maguire
taxi-driver hippocampus audit (2000 PNAS, 2006 Hippocampus, 2011 Curr Biol).

Co-authored. CC0. Stdlib only, no network.

  python3 extract.py --verify SRC_DIR
        SRC_DIR holds the locally fetched files named in quotes.json
        `sources` (not committed; sha256 in manifest.json). Checks each file's
        sha256, checks every quote verbatim (whitespace ignored) against
        its source text, counts the stress-related search terms in each
        source, and writes located.json and EXTRACT.md.
  python3 extract.py --check
        No sources needed. Checks structure: required items present, every
        UNKNOWN entry names its field and what was searched, every quote was
        located, every recorded zero-hit search is still recorded as zero,
        and EXTRACT.md equals the render of quotes.json + located.json.

A quote that is not found verbatim is a failure, never silently kept.
"""
import hashlib
import html
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
QUOTES = HERE / "quotes.json"
LOCATED = HERE / "located.json"
EXTRACT = HERE / "EXTRACT.md"
MANIFEST = HERE / "manifest.json"
REQUIRED_ITEMS = [1, 2, 3, 4, 5, "selection", "context"]
SEARCH_TERMS = ["stress", "cortisol", "passenger", "emotion", "fare"]
ZERO_HIT_SOURCES = ["M2000", "W2011"]  # item 4 records zero hits for these


def norm(s):
    return " ".join(s.split())


def squash(s):
    """For matching only: drop all whitespace. Tag stripping inserts spaces
    around inline citation links ("( 14 )" for "(14)"), so a quote is matched
    character for character with whitespace ignored. No other character is
    changed or dropped."""
    return "".join(s.split())


def source_text(path, kind):
    raw = path.read_text(encoding="utf-8")
    if kind == "html":
        m = re.search(r'<section[^>]*class="body main-article-body"', raw)
        if m:
            raw = raw[m.start():]
            end = raw.find('<section class="ref-list')
            if end > 0:
                raw = raw[:end]
        raw = re.sub(r"<(script|style)[^>]*>.*?</\1>", "", raw, flags=re.S)
    elif kind == "jats":
        raw = re.sub(r"<ref-list.*?</ref-list>", "", raw, flags=re.S)
    elif kind == "epmc_abstract":
        rec = json.loads(raw)["resultList"]["result"][0]
        return norm(" ".join(x for x in (rec.get("title"), rec.get("abstractText")) if x))
    else:
        raise ValueError(f"unknown kind {kind}")
    raw = re.sub(r"<[^>]+>", " ", raw)
    return norm(html.unescape(raw))


def entries(data):
    for it in data["items"]:
        for i, e in enumerate(it["entries"], 1):
            yield f"{it['item']}.{i}", it, e


def verify(src_dir):
    data = json.loads(QUOTES.read_text(encoding="utf-8"))
    man = json.loads(MANIFEST.read_text(encoding="utf-8"))
    want = {f["file"]: f["sha256"] for f in man["fetched"]}
    texts, hits = {}, {}
    for sid, s in data["sources"].items():
        p = Path(src_dir) / s["file"]
        got = hashlib.sha256(p.read_bytes()).hexdigest()
        if got != want[s["file"]]:
            sys.exit(f"FAIL sha256 {s['file']}: {got} != {want[s['file']]}")
        t = source_text(p, s["kind"])
        texts[sid] = t
        low = t.lower()
        hits[sid] = {w: len(re.findall(r"\b" + w, low)) for w in SEARCH_TERMS}
    located, bad = {}, []
    for k, it, e in entries(data):
        if e["quote"] is None:
            continue
        ok = squash(e["quote"]) in squash(texts[e["source"]])
        located[k] = {"source": e["source"], "verbatim": ok}
        if not ok:
            bad.append(k)
    out = {"schema": "study-aperture/located/2",
           "matching": "quote is a substring of the source text with all whitespace removed from both (tags stripped, entities unescaped); every other character must match",
           "quotes": located,
           "search_term_hits": hits}
    LOCATED.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    EXTRACT.write_text(render(data, out), encoding="utf-8")
    if bad:
        sys.exit("FAIL not verbatim: " + ", ".join(bad))
    print(f"verify: {len(located)} quotes verbatim; hits {hits}")


def render(data, loc):
    lines = ["Status: generated by `extract.py --verify` from `quotes.json` and `located.json`. Quotes only, no reasoning; reasoning is in `CHECKS.md`. Not established: anything in the 2006 paper's body or the 2011 supplement (not read).", "",
             "# Extract: Maguire et al. 2000, Maguire et al. 2006, Woollett & Maguire 2011", ""]
    lines.append("## Sources")
    lines.append("")
    for sid, s in data["sources"].items():
        lines.append(f"- **{sid}** ({s['reach']}): {s['cite']}")
    lines.append("")
    for it in data["items"]:
        tag = it["item"] if isinstance(it["item"], int) else "-" + it["item"]
        lines.append(f"## E{tag}. {it['topic']}")
        lines.append("")
        for i, e in enumerate(it["entries"], 1):
            k = f"{it['item']}.{i}"
            if e["quote"] is None:
                lines.append(f"- `{k}` **{e['source']}** UNKNOWN: {e['field']}. Searched: {e['searched']}")
            else:
                mark = "verbatim" if loc["quotes"][k]["verbatim"] else "NOT FOUND"
                lines.append(f"- `{k}` **{e['source']}**, {e['section']} ({mark}): \"{e['quote']}\"")
        lines.append("")
    lines.append("## Search-term hits (case-insensitive, word-initial)")
    lines.append("")
    lines.append("| source | " + " | ".join(SEARCH_TERMS) + " |")
    lines.append("|---|" + "---|" * len(SEARCH_TERMS))
    for sid, h in loc["search_term_hits"].items():
        lines.append(f"| {sid} | " + " | ".join(str(h[w]) for w in SEARCH_TERMS) + " |")
    lines.append("")
    return "\n".join(lines)


def check():
    data = json.loads(QUOTES.read_text(encoding="utf-8"))
    loc = json.loads(LOCATED.read_text(encoding="utf-8"))
    errs = []
    items = [it["item"] for it in data["items"]]
    for r in REQUIRED_ITEMS:
        if r not in items:
            errs.append(f"missing item {r}")
    for k, it, e in entries(data):
        if e["source"] not in data["sources"]:
            errs.append(f"{k}: unknown source {e['source']}")
        if e["quote"] is None:
            if not e.get("field") or not e.get("searched"):
                errs.append(f"{k}: UNKNOWN without field/searched")
        else:
            if not e.get("section"):
                errs.append(f"{k}: quote without section")
            if not loc["quotes"].get(k, {}).get("verbatim"):
                errs.append(f"{k}: quote not located verbatim")
    for sid in ZERO_HIT_SOURCES:
        h = loc["search_term_hits"].get(sid)
        if h is None or any(h[w] for w in SEARCH_TERMS):
            errs.append(f"{sid}: item 4 records zero search hits but located.json says {h}")
    if EXTRACT.read_text(encoding="utf-8") != render(data, loc):
        errs.append("EXTRACT.md differs from render of quotes.json + located.json")
    if errs:
        for e in errs:
            print("FAIL", e)
        return 1
    n = sum(1 for _, _, e in entries(data) if e["quote"] is not None)
    u = sum(1 for _, _, e in entries(data) if e["quote"] is None)
    print(f"check: {n} quotes located, {u} UNKNOWN entries, structure OK")
    return 0


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--verify":
        verify(sys.argv[2])
    elif sys.argv[1:] == ["--check"]:
        sys.exit(check())
    else:
        print(__doc__)
        sys.exit(2)
